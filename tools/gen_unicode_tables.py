#!/usr/bin/env python3
"""gen_unicode_tables.py - writes src/tokenizer/unicode_tables.inc (and unicode_tables.meta.json).

The byte-level BPE tokenizers split text with a regular expression that uses \\p{L} (letters), \\p{N} (numbers)
and \\s (white space). C++ has no Unicode database, so the ranges are generated here from Python's unicodedata
and compiled into the engine:
  letters      general category L*  (Lu, Ll, Lt, Lm, Lo)
  numbers      general category N*  (Nd, Nl, No)
  white space  the Unicode White_Space property (the list is short and fixed)

The metadata file records the Unicode version, a SHA-256 checksum of the table file and the code points that were
still unassigned in that version; tests/verify_unicode.py uses it to tell a damaged table from a Python that simply
knows a newer Unicode version.

Run it again only if a different Unicode version is wanted (for example to match the Python you test with):
  python tools/gen_unicode_tables.py
"""
from __future__ import annotations

import argparse
import hashlib
import json
import sys
import unicodedata
from pathlib import Path

WHITE_SPACE = [(0x09, 0x0D), (0x20, 0x20), (0x85, 0x85), (0xA0, 0xA0), (0x1680, 0x1680), (0x2000, 0x200A),
               (0x2028, 0x2029), (0x202F, 0x202F), (0x205F, 0x205F), (0x3000, 0x3000)]


def ranges(predicate) -> list[tuple[int, int]]:
    out: list[tuple[int, int]] = []
    start = None
    for cp in range(0x110000):
        inside = predicate(cp)
        if inside and start is None:
            start = cp
        elif not inside and start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def emit(name: str, rs: list[tuple[int, int]]) -> str:
    rows = [f"    {{0x{lo:X}, 0x{hi:X}}}," for lo, hi in rs]
    return f"static const CodePointRange {name}[] = {{\n" + "\n".join(rows) + "\n};\n"


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    ap.add_argument("--out-dir", default=str(Path(__file__).resolve().parent.parent / "src" / "tokenizer"))
    ap.add_argument("--database", choices=["current", "3.2"], default="current",
                    help="'3.2' uses Unicode 3.2 (only to test the version-drift handling of tests/verify_unicode.py)")
    args = ap.parse_args()

    db = unicodedata if args.database == "current" else unicodedata.ucd_3_2_0
    version = db.unidata_version

    def category(cp: int) -> str:
        return "Cs" if 0xD800 <= cp <= 0xDFFF else db.category(chr(cp))

    letters = ranges(lambda cp: category(cp).startswith("L"))
    numbers = ranges(lambda cp: category(cp).startswith("N"))
    unassigned = ranges(lambda cp: category(cp) == "Cn")
    text = (f"// GENERATED by tools/gen_unicode_tables.py from Python's unicodedata (Unicode {version}).\n"
            "// Do not edit by hand. Each row is an inclusive range of code points.\n\n"
            + emit("kLetterRanges", letters) + "\n" + emit("kNumberRanges", numbers) + "\n"
            + emit("kSpaceRanges", WHITE_SPACE))
    out = Path(args.out_dir)
    out.mkdir(parents=True, exist_ok=True)
    (out / "unicode_tables.inc").write_text(text, encoding="utf-8")
    digest = hashlib.sha256((out / "unicode_tables.inc").read_bytes()).hexdigest()
    (out / "unicode_tables.meta.json").write_text(
        json.dumps({"unicode_version": version, "sha256": digest, "unassigned": unassigned}), encoding="utf-8")
    print(f"wrote {out}: {len(letters)} letter ranges, {len(numbers)} number ranges, {len(WHITE_SPACE)} space ranges, "
          f"{len(unassigned)} unassigned ranges (Unicode {version})")


if __name__ == "__main__":
    sys.exit(main())
