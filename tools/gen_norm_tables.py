#!/usr/bin/env python3
"""gen_norm_tables.py - writes src/tokenizer/unicode_norm_tables.inc (and unicode_norm_tables.meta.json).

The tables behind the NFC normalizer (Unicode canonical decomposition followed by canonical composition), which
the Qwen tokenizers apply to the text before anything else. All data comes from Python's unicodedata:

  kCccRanges   canonical combining class of every code point whose class is not 0 (inclusive ranges, same class)
  kDecomp      canonical decomposition mappings as in UnicodeData.txt (one level; 1 or 2 code points, no <compat> ones)
               Hangul syllables are not listed: they are decomposed and composed by arithmetic
  kCompose     the primary composites: pairs (first, second) -> composite, for every code point whose decomposition
               has two parts and which is stable under NFC (that is exactly "not excluded from composition")

Run it again only if another Unicode version is wanted:
  python tools/gen_norm_tables.py
"""
from __future__ import annotations

import hashlib
import json
import sys
import unicodedata
from pathlib import Path

HANGUL_FIRST, HANGUL_LAST = 0xAC00, 0xD7A3


def main() -> None:
    out_dir = Path(__file__).resolve().parent.parent / "src" / "tokenizer"
    ccc_ranges: list[tuple[int, int, int]] = []
    decomp: list[tuple[int, tuple[int, ...]]] = []
    compose: list[tuple[int, int, int]] = []
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        ch = chr(cp)
        c = unicodedata.combining(ch)
        if c:
            if ccc_ranges and ccc_ranges[-1][1] == cp - 1 and ccc_ranges[-1][2] == c:
                ccc_ranges[-1] = (ccc_ranges[-1][0], cp, c)
            else:
                ccc_ranges.append((cp, cp, c))
        d = unicodedata.decomposition(ch)
        if not d or d.startswith("<") or HANGUL_FIRST <= cp <= HANGUL_LAST:
            continue
        parts = tuple(int(x, 16) for x in d.split())
        assert len(parts) in (1, 2), (hex(cp), d)
        decomp.append((cp, parts))
        if len(parts) == 2 and unicodedata.normalize("NFC", ch) == ch:
            compose.append((parts[0], parts[1], cp))
    compose.sort()

    lines = [f"// GENERATED by tools/gen_norm_tables.py from Python's unicodedata (Unicode {unicodedata.unidata_version}).",
             "// Do not edit by hand.", "",
             "struct CccRange { std::uint32_t lo, hi; std::uint8_t ccc; };",
             "struct DecompEntry { std::uint32_t cp, first, second; };   // second == 0: a singleton mapping",
             "struct ComposeEntry { std::uint32_t first, second, composite; };", "",
             "static const CccRange kCccRanges[] = {"]
    lines += [f"    {{0x{lo:X}, 0x{hi:X}, {c}}}," for lo, hi, c in ccc_ranges]
    lines += ["};", "", "static const DecompEntry kDecomp[] = {"]
    lines += [f"    {{0x{cp:X}, 0x{p[0]:X}, 0x{(p[1] if len(p) > 1 else 0):X}}}," for cp, p in decomp]
    lines += ["};", "", "static const ComposeEntry kCompose[] = {   // sorted by (first, second)"]
    lines += [f"    {{0x{a:X}, 0x{b:X}, 0x{c:X}}}," for a, b, c in compose]
    lines += ["};", ""]
    path = out_dir / "unicode_norm_tables.inc"
    path.write_text("\n".join(lines), encoding="utf-8")
    digest = hashlib.sha256(path.read_bytes()).hexdigest()
    unassigned: list[list[int]] = []   # code points still unassigned in this version (tests excuse them if Python is newer)
    for cp in range(0x110000):
        if not (0xD800 <= cp <= 0xDFFF) and unicodedata.category(chr(cp)) == "Cn":
            if unassigned and unassigned[-1][1] == cp - 1:
                unassigned[-1][1] = cp
            else:
                unassigned.append([cp, cp])
    (out_dir / "unicode_norm_tables.meta.json").write_text(
        json.dumps({"unicode_version": unicodedata.unidata_version, "sha256": digest, "unassigned": unassigned}), encoding="utf-8")
    print(f"wrote {path}: {len(ccc_ranges)} combining-class ranges, {len(decomp)} decompositions, "
          f"{len(compose)} compositions (Unicode {unicodedata.unidata_version})")


if __name__ == "__main__":
    sys.exit(main())
